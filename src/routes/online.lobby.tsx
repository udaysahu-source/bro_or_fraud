import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { useState, useRef } from "react";
import { buzz, success as hapticSuccess, error as hapticError, reveal as hapticReveal } from "@/lib/haptics";
import { createRoomOptimistic } from "@/lib/room";

export const Route = createFileRoute("/online/lobby")({
  component: OnlineLobby,
  head: () => ({
    meta: [
      { title: "Online Lobby — Bro or Fraud?" },
      { name: "description", content: "Join or create an online multiplayer room." },
    ],
  }),
});

function generateRoomCode(): string {
  const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
  let code = "";
  for (let i = 0; i < 4; i++) {
    code += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return code;
}

export function OnlineLobby() {
  const navigate = useNavigate();
  const [joinDigits, setJoinDigits] = useState<string[]>(["", "", "", ""]);
  const [isJoining, setIsJoining] = useState(false);
  const [isCreating, setIsCreating] = useState(false);
  const joinRefs = useRef<Array<HTMLInputElement | null>>([]);

  const handleDigitChange = (index: number, val: string) => {
    const clean = val.replace(/[^A-Za-z0-9]/g, "").toUpperCase().slice(-1);
    setJoinDigits((prev) => {
      const next = [...prev];
      next[index] = clean;
      return next;
    });

    if (clean && index < 3) {
      joinRefs.current[index + 1]?.focus();
    }
  };

  const handleCreateRoom = () => {
    buzz([30, 20, 30]);
    setIsCreating(true);
    hapticReveal();
    
    // Simulate optimistic room creation, then navigate to room
    const code = generateRoomCode();
    setTimeout(() => {
      hapticSuccess();
      navigate({
        to: "/online/room/$code",
        params: { code },
      });
      setIsCreating(false);
    }, 600);
  };

  const handleJoinSubmit = () => {
    const code = joinDigits.join("").toUpperCase();
    if (code.length !== 4) return;
    buzz([20, 20]);
    setIsJoining(true);

    setTimeout(() => {
      hapticSuccess();
      navigate({
        to: "/online/room/$code",
        params: { code },
      });
      setIsJoining(false);
    }, 600);
  };

  return (
    <div className="min-h-dvh bg-void text-foreground">
      <div className="mx-auto flex min-h-dvh w-full max-w-md flex-col px-5 pt-6 pb-8">
        <header className="flex items-center justify-between">
          <Link to="/" onClick={() => buzz(15)} className="text-xs font-bold uppercase tracking-widest text-muted-foreground">
            ← Home
          </Link>
          <span className="text-xs font-bold uppercase tracking-widest text-muted-foreground">
            Online Matchmaking
          </span>
        </header>

        <section className="mt-8 text-center">
          <p className="text-xs font-black uppercase tracking-[0.4em] text-magenta">
            // serverless play
          </p>
          <h1 className="mt-2 text-4xl font-black uppercase leading-[0.9] text-off-white">
            Online <span className="text-lime">Lobby 🌐</span>
          </h1>
          <p className="mt-2 text-sm text-muted-foreground max-w-[28ch] mx-auto">
            Play with your friends remotely on separate devices for free.
          </p>
        </section>

        <div className="flex-1 flex flex-col justify-center gap-6 mt-6">
          {/* Create Room Card */}
          <div className="rounded-2xl border-2 border-white/10 bg-surface p-5 brutal-shadow-yellow relative overflow-hidden">
            <h2 className="text-lg font-black uppercase text-lime">Host a Room</h2>
            <p className="text-xs text-muted-foreground mt-1">
              Start a new game session, choose word packs, and invite players.
            </p>
            <button
              onClick={handleCreateRoom}
              disabled={isCreating}
              className="mt-4 w-full rounded-xl bg-lime px-6 py-4 text-center text-md font-black uppercase tracking-wide text-void border-2 border-void tactile tactile-press disabled:opacity-50"
            >
              {isCreating ? "Generating Room..." : "Create New Room →"}
            </button>
          </div>

          {/* Join Room Card */}
          <div className="rounded-2xl border-2 border-white/10 bg-surface p-5 brutal-shadow-pink">
            <h2 className="text-lg font-black uppercase text-magenta">Join Existing</h2>
            <p className="text-xs text-muted-foreground mt-1">
              Enter the 4-digit code generated by the host.
            </p>

            <div className="mt-4 flex justify-center gap-2">
              {[0, 1, 2, 3].map((i) => (
                <input
                  key={i}
                  ref={(el) => { joinRefs.current[i] = el; }}
                  maxLength={1}
                  value={joinDigits[i]}
                  onChange={(e) => handleDigitChange(i, e.target.value)}
                  onKeyDown={(e) => {
                    if (e.key === "Backspace" && !joinDigits[i] && i > 0) {
                      joinRefs.current[i - 1]?.focus();
                    }
                  }}
                  className="grid size-12 place-items-center rounded-xl border-2 border-border bg-void text-center text-xl font-black text-foreground caret-lime focus:border-lime focus:outline-none uppercase"
                />
              ))}
            </div>

            {joinDigits.every((d) => d) && (
              <button
                onClick={handleJoinSubmit}
                disabled={isJoining}
                className="mt-4 w-full rounded-xl bg-magenta px-6 py-3.5 text-center text-sm font-black uppercase tracking-widest text-white border-2 border-void tactile tactile-press disabled:opacity-50"
              >
                {isJoining ? "Connecting..." : `Join Room ${joinDigits.join("")} →`}
              </button>
            )}
          </div>
        </div>

        <p className="pt-6 text-center text-[10px] font-black uppercase tracking-[0.25em] text-muted-foreground">
          stateless matchmaking · powered by peerjs
        </p>
      </div>
    </div>
  );
}
